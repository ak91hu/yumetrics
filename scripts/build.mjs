import { readdirSync, mkdirSync, cpSync, existsSync, rmSync, readFileSync, writeFileSync } from 'node:fs';
import { resolve, relative, isAbsolute } from 'node:path';
import { fileURLToPath } from 'node:url';
import { execFileSync } from 'node:child_process';
import assert from 'node:assert/strict';
import { STATIC_FILES } from '../lib/http.mjs';
import { guideMarkup } from '../lib/i18n.mjs';

const root = fileURLToPath(new URL('..', import.meta.url)), out = resolve(root, 'dist');
const within = relative(root, out); assert.ok(within && !within.startsWith('..') && !isAbsolute(within) && out === resolve(root, 'dist'));
execFileSync(process.execPath,[resolve(root,'scripts/build-docs.mjs')],{stdio:'inherit'});
for (const folder of ['lib', 'public']) for (const name of readdirSync(resolve(root, folder)).filter(name => name.endsWith('.mjs'))) execFileSync(process.execPath, ['--check', resolve(root, folder, name)]);
execFileSync(process.execPath, ['--check', resolve(root, 'server.mjs')]);
for (const [file] of Object.values(STATIC_FILES)) assert.ok(existsSync(resolve(root, 'public', file)), `Missing asset: ${file}`);
assert.ok(existsSync(resolve(root, 'public/login.html')));
rmSync(out, { recursive: true, force: true }); mkdirSync(out);
for (const name of ['server.mjs', 'lib', 'public', 'postgres', 'drizzle', 'package.json', 'package-lock.json']) cpSync(resolve(root, name), resolve(out, name), { recursive: true });
const documentation = resolve(out, 'documentation'); mkdirSync(documentation);
const guide = readFileSync(resolve(root, 'public/help.html'), 'utf8');
writeFileSync(resolve(documentation, 'index.html'), guideMarkup(guide, 'hu', true));
writeFileSync(resolve(documentation, 'english.html'), guideMarkup(guide, 'en', true));
cpSync(resolve(root, 'public/favicon.svg'), resolve(documentation, 'favicon.svg'));
assert.ok(!existsSync(resolve(out, '.env')) && !existsSync(resolve(out, 'worker')));
console.log('Northflank Node alkalmazás: dist/server.mjs · titkok és felhasználói adatok nélkül.');
console.log('Önállóan publikálható útmutató: dist/documentation/index.html');
